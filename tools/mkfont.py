#!/usr/bin/env python3
"""Extract the font5x7 bitmap table from EigenScript's ext_gfx.c into a
C header for the EigenOS framebuffer console (M9.5).

Same single-source-of-truth pattern as the ROM bundle: the sibling
checkout owns the glyphs (gfx_text draws with them hosted), EigenOS
bakes a copy at build time so the on-metal console and the hosted
window render identical text.

usage: mkfont.py <path-to-ext_gfx.c> <output.h>
"""
import re
import sys


def main():
    src_path, out_path = sys.argv[1], sys.argv[2]
    src = open(src_path, encoding="utf-8").read()

    m = re.search(
        r"font5x7\[95\]\[7\]\s*=\s*\{(.*?)\n\};", src, re.DOTALL)
    if not m:
        sys.exit("mkfont: font5x7[95][7] table not found in " + src_path)
    body = m.group(1)

    rows = re.findall(r"\{([0-9xXa-fA-F,\s]+)\}", body)
    if len(rows) != 95:
        sys.exit(f"mkfont: expected 95 glyphs, found {len(rows)}")

    glyphs = []
    for row in rows:
        vals = [int(v, 0) for v in row.split(",") if v.strip()]
        if len(vals) != 7:
            sys.exit(f"mkfont: glyph with {len(vals)} rows (want 7)")
        if any(v > 0x1F for v in vals):
            sys.exit("mkfont: glyph row wider than 5 bits")
        glyphs.append(vals)

    with open(out_path, "w", encoding="utf-8") as out:
        out.write(
            "/* Generated by tools/mkfont.py from EigenScript ext_gfx.c —\n"
            " * the same 5x7 font gfx_text uses hosted. Do not edit. */\n"
            "static const unsigned char font5x7[95][7] = {\n")
        for vals in glyphs:
            out.write("    {" + ",".join(f"0x{v:02X}" for v in vals) + "},\n")
        out.write("};\n")
    print(f"mkfont: {len(glyphs)} glyphs -> {out_path}")


if __name__ == "__main__":
    main()
