#!/usr/bin/env python3
"""Generate the ROM bundle (M7.5): .eigs sources baked into the kernel
image as C byte arrays, served to the runtime through the
eigs_set_source_provider seam so `import` works with no filesystem.

usage: mkbundle.py OUT.c FILE.eigs [FILE.eigs ...]

Module name = file stem (lib/math.eigs -> "math"; demos/life.eigs ->
"life"). Byte arrays (not string literals) so no escaping bugs are
possible; each is NUL-terminated. Duplicate stems are a hard error.
"""
import sys, os

def main():
    if len(sys.argv) < 3:
        sys.exit("usage: mkbundle.py OUT.c FILE.eigs ...")
    out_path, files = sys.argv[1], sys.argv[2:]
    entries = []
    seen = {}
    for f in files:
        name = os.path.splitext(os.path.basename(f))[0]
        if name in seen:
            sys.exit(f"mkbundle: duplicate module name '{name}' "
                     f"({seen[name]} vs {f})")
        seen[name] = f
        data = open(f, 'rb').read()
        entries.append((name, f, data))

    with open(out_path, 'w') as o:
        o.write("/* GENERATED by tools/mkbundle.py — do not edit.\n"
                " * The ROM bundle (M7.5): module sources served through the\n"
                " * eigs_set_source_provider seam. Kernel-flags code (no libc:\n"
                " * local strcmp below). */\n\n")
        for i, (name, src, data) in enumerate(entries):
            o.write(f"/* {src} ({len(data)} bytes) */\n")
            o.write(f"static const char bundle_src_{i}[] = {{")
            for j, b in enumerate(data):
                if j % 16 == 0:
                    o.write("\n    ")
                o.write(f"{b},")
            o.write("0};\n\n")
        o.write("static const struct { const char *name; const char *src; }"
                " BUNDLE[] = {\n")
        for i, (name, src, data) in enumerate(entries):
            o.write(f'    {{"{name}", bundle_src_{i}}},\n')
        o.write("};\n\n")
        o.write(
"static int bundle_streq(const char *a, const char *b) {\n"
"    while (*a && *a == *b) { a++; b++; }\n"
"    return *a == *b;\n"
"}\n\n"
"const char *eigs_bundle_lookup(const char *name) {\n"
"    if (!name) return 0;\n"
"    for (unsigned i = 0; i < sizeof(BUNDLE)/sizeof(BUNDLE[0]); i++)\n"
"        if (bundle_streq(BUNDLE[i].name, name)) return BUNDLE[i].src;\n"
"    return 0;\n"
"}\n\n"
"int eigs_bundle_count(void) { return (int)(sizeof(BUNDLE)/sizeof(BUNDLE[0])); }\n")
    total = sum(len(d) for _, _, d in entries)
    print(f"mkbundle: {len(entries)} modules, {total} bytes -> {out_path}")

main()
